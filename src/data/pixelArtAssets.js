// HELPER UNIVERSAL DE RESPOSTA PIXEL PARA QUALQUER MODELO 3D
// ============================================================================
export function getUniversalModelPixels(modelId = 'capivara', angle = 0, variantId = 1) {
  if (modelId === 'capivara') {
    return CAPIVARA_8VISTAS_PIXELS[angle] || CAPIVARA_8VISTAS_PIXELS[0] || [];
  }
  if (modelId === 'espada_bambu') {
    return SWORD_8VISTAS_PIXELS[angle] || SWORD_8VISTAS_PIXELS[0] || [];
  }
  if (modelId === 'machado_runico') {
    return MACHADO_8VISTAS_PIXELS[angle] || MACHADO_8VISTAS_PIXELS[0] || [];
  }
  if (modelId === 'bau_tesouro') {
    return BAU_8VISTAS_PIXELS[angle] || BAU_8VISTAS_PIXELS[0] || [];
  }
  if (modelId === 'elmo_prata') {
    return ELMO_8VISTAS_PIXELS[angle] || ELMO_8VISTAS_PIXELS[0] || [];
  }

  // Gerador Procedural Determinístico para qualquer novo modelo criado pelo usuário
  const seed = (modelId || 'objeto').split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const angOffset = Math.floor((angle || 0) / 45);
  const primaryColor = ['#38bdf8', '#fbbf24', '#34d399', '#f472b6', '#a78bfa'][seed % 5];
  const darkColor = '#0f172a';
  const midColor = '#334155';
  const lightColor = '#f8fafc';

  const px = [];
  // Gera silhueta 3D projetada na grade 28x28
  for (let dy = 7; dy <= 17; dy++) {
    const width = 3 + ((seed + dy) % 4);
    const centerX = 14 + Math.round(Math.sin((angOffset * Math.PI) / 4) * 2);
    for (let dx = centerX - width; dx <= centerX + width; dx++) {
      let c = midColor;
      if (dx === centerX - width || dx === centerX + width || dy === 7 || dy === 17) c = darkColor;
      else if (dx === centerX) c = primaryColor;
      else if (dx > centerX) c = lightColor;
      px.push({ x: dx, y: dy, c });
    }
  }
  return px;
}

